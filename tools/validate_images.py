#!/usr/bin/env python3
"""Validate candidate Wikimedia Commons files and emit js/data/images.js.

Usage: python3 -I tools/validate_images.py candidates1.json [candidates2.json ...]
Each JSON file is a list of {key, file, caption, topic?, tradition?, conf?, use?}.
Only files that exist and carry a free licence (PD / CC0 / CC BY / CC BY-SA) are kept.
"""
import html, json, re, sys, time, urllib.error, urllib.parse, urllib.request, pathlib

API = 'https://commons.wikimedia.org/w/api.php'
UA = 'RootsEducationalAtlas/1.0 (local educational project)'
OK_LIC = re.compile(r'^(public domain|pd|cc0|cc by(-sa)?( \d\.\d)?|cc-by(-sa)?|attribution|no restrictions)', re.I)


def strip(s):
    s = re.sub(r'<[^>]+>', '', s or '')
    return html.unescape(re.sub(r'\s+', ' ', s)).strip()


def query(titles):
    params = {
        'action': 'query', 'format': 'json', 'prop': 'imageinfo', 'redirects': 1,
        'iiprop': 'url|extmetadata|size', 'iiurlwidth': 960,
        'iiextmetadatafilter': 'LicenseShortName|Artist|Credit|ImageDescription|DateTimeOriginal',
        'titles': '|'.join(titles),
    }
    req = urllib.request.Request(API + '?' + urllib.parse.urlencode(params), headers={'User-Agent': UA})
    for attempt in range(8):
        try:
            with urllib.request.urlopen(req, timeout=40) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code not in (429, 503):
                raise
            wait = int(e.headers.get('Retry-After') or 0) or 5 * (attempt + 1)
            print(f'  rate-limited, waiting {wait}s', file=sys.stderr)
            time.sleep(min(wait, 60))
    raise RuntimeError('Commons API kept rate-limiting')


def main(paths):
    cands = []
    for p in paths:
        cands += json.load(open(p))
    norm = lambda t: ('File:' + t.split(':', 1)[-1]).replace('_', ' ').strip()
    for c in cands:
        c['file'] = norm(c['file'])
    titles = list(dict.fromkeys(c['file'] for c in cands))
    info = {}
    for i in range(0, len(titles), 25):
        batch = titles[i:i + 25]
        d = query(batch)
        q = d.get('query', {})
        alias = {}
        for n in q.get('normalized', []) + q.get('redirects', []):
            alias[n['to']] = n['from']
        for page in q.get('pages', {}).values():
            t = page.get('title')
            ii = (page.get('imageinfo') or [None])[0]
            if not ii:
                continue
            md = ii.get('extmetadata', {})
            rec = {
                'thumb': (ii.get('thumburl') or ii.get('url') or '').split('?')[0], 'full': (ii.get('url') or '').split('?')[0], 'page': ii.get('descriptionurl'),
                'w': ii.get('thumbwidth') or ii.get('width'), 'h': ii.get('thumbheight') or ii.get('height'),
                'license': strip(md.get('LicenseShortName', {}).get('value')),
                'artist': strip(md.get('Artist', {}).get('value'))[:120],
            }
            info[t] = rec
            if t in alias:
                info[alias[t]] = rec
        time.sleep(2)
    out, bad = [], []
    seen = set()
    for c in cands:
        r = info.get(c['file'])
        if not r:
            bad.append((c['file'], 'missing')); continue
        if not OK_LIC.search(r['license'] or ''):
            bad.append((c['file'], 'licence: ' + (r['license'] or '?'))); continue
        if (c['key'], c['file']) in seen:
            continue
        seen.add((c['key'], c['file']))
        if (r['full'] or '').lower().endswith(('.tif', '.tiff', '.pdf', '.djvu')) and not r['thumb']:
            bad.append((c['file'], 'format')); continue
        out.append({**{k: c.get(k) for k in ('key', 'topic', 'tradition', 'caption', 'conf', 'use') if c.get(k)},
                    'file': c['file'], **r})
    root = pathlib.Path(__file__).resolve().parent.parent
    js = ('// Generated by tools/validate_images.py from Wikimedia Commons (free licences only). Do not edit by hand.\n'
          'export const IMAGES = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
    (root / 'js' / 'data' / 'images.js').write_text(js)
    print(f'kept {len(out)} / {len(cands)}')
    for f, why in bad:
        print('DROP', why, '|', f)


if __name__ == '__main__':
    main(sys.argv[1:])
